"""Documentation branch publisher: artifacts live in their own git branch.

Generated artifacts (maps, site, video, agent docs, wiki) change the
language GitHub reports for a project -- a C repository can show up as
"HTML" once the generated pages are committed. Two fixes ship here:

1. ``ensure_gitattributes`` marks every generated output directory as
   ``linguist-generated`` so language statistics always describe the
   source tree, no matter where artifacts live.
2. ``publish`` stages the static site (``readmenator . pages`` output)
   into an orphan git branch (``DOC_BRANCH_NAME``) and pushes it, so
   GitHub Pages can deploy "from branch" and the main branch stays free
   of generated artifacts entirely.

The Pages URL is inferred from the origin remote (``github.com/user/repo``
-> ``https://user.github.io/repo/``), overridable via ``DOC_PAGES_URL``,
and is what the README injection links so following a link from the
README lands on the deployed documentation instead of a dead repo path.
Git is driven with argument lists only (no shell), bounded timeouts, and
an injectable runner for tests.
"""

from __future__ import annotations

import logging
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, List, Optional

from readmenator._config import Config
from readmenator._gitmeta import read_git_head

logger = logging.getLogger(__name__)

Runner = Callable[..., subprocess.CompletedProcess]

_REMOTE_RE = re.compile(r"^(?:https://|ssh://git@|git@)([^/:]+)[/:]([\w.\-]+)/([\w.\-]+?)(?:\.git)?/?$")
_GITHUB_WEB_RE = re.compile(r"^https://github\.com/[\w.\-]+/[\w.\-]+/?$")
_GA_BEGIN = "# readmenator:gitattributes:begin"
_GA_END = "# readmenator:gitattributes:end"


@dataclass
class DocsBranchResult:
    """Outcome of a documentation branch publish.

    Attributes:
        branch: Branch name the site was committed to.
        files: Site files staged (relative to the branch root).
        pushed: Whether the commit was pushed to the remote.
        remote: Remote URL used ("" in dry runs without a remote).
        pages_url: Inferred or configured Pages URL ("" when unknown).
        output_dir: Directory holding the staged site.
        commit: Source commit the snapshot was generated from.
        message: Human-readable status line.
    """

    branch: str = ""
    files: List[str] = field(default_factory=list)
    pushed: bool = False
    remote: str = ""
    pages_url: str = ""
    output_dir: str = ""
    commit: str = ""
    message: str = ""


class DocsBranchPublisher:
    """Stages the static site into a dedicated git branch for Pages."""

    def __init__(self, config: Config, runner: Optional[Runner] = None) -> None:
        """Store configuration and the subprocess runner (injectable for tests).

        Args:
            config: DOC_*/GITATTRIBUTES_* settings and output directories.
            runner: Callable compatible with ``subprocess.run``.
        """
        self._config = config
        self._run = runner or subprocess.run

    def generated_paths(self) -> List[str]:
        """Return project-relative output paths that count as generated."""
        cfg = self._config
        dirs = [
            cfg.AGENT_OUTPUT_DIR, cfg.WIKI_OUTPUT_DIR, cfg.RULE_GEN_OUTPUT_DIR,
            cfg.DIAGRAM_OUTPUT_DIR, cfg.SITE_DIR, cfg.CACHE_DIR,
            cfg.GRAPHRAG_OUTPUT_DIR, cfg.COMPONENTS_OUTPUT_DIR, cfg.APIDOCS_OUTPUT_DIR,
            cfg.DIAGRAM_PAGES_DIR, cfg.DOC_DRY_RUN_DIR,
        ]
        paths = [d.strip("/") for d in dirs if d.strip("/") and "/" not in d.strip("/")]
        files = [p for p in (cfg.SITE_VIDEO_FILENAME, cfg.SITE_VIDEO_POSTER_FILENAME) if p.strip()]
        return sorted(set(paths + files))

    def _gitattributes_block(self) -> List[str]:
        """Render the linguist-generated block lines."""
        cfg = self._config
        dirs = sorted({
            d.strip("/")
            for d in (
                cfg.AGENT_OUTPUT_DIR, cfg.WIKI_OUTPUT_DIR, cfg.RULE_GEN_OUTPUT_DIR,
                cfg.DIAGRAM_OUTPUT_DIR, cfg.SITE_DIR, cfg.CACHE_DIR,
                cfg.GRAPHRAG_OUTPUT_DIR, cfg.COMPONENTS_OUTPUT_DIR, cfg.APIDOCS_OUTPUT_DIR,
                cfg.DIAGRAM_PAGES_DIR, cfg.DOC_DRY_RUN_DIR,
            ) if d.strip("/") and "/" not in d.strip("/")
        })
        lines = [_GA_BEGIN, "# Generated by readmenator; excluded from language statistics."]
        for directory in dirs:
            lines.append(f"/{directory}/** linguist-generated=true")
        for path in (cfg.SITE_VIDEO_FILENAME, cfg.SITE_VIDEO_POSTER_FILENAME):
            if path.strip():
                lines.append(f"/{path.strip('/')} linguist-generated=true")
        lines.append(_GA_END)
        return lines

    def ensure_gitattributes(self, project_root: str) -> bool:
        """Add or refresh the linguist-generated block in .gitattributes.

        Args:
            project_root: Project root directory.

        Returns:
            True when the file was created or changed, False when intact.
        """
        if not self._config.GITATTRIBUTES_ENABLED:
            return False
        target = Path(project_root) / self._config.GITATTRIBUTES_FILENAME
        if target.is_symlink():
            logger.warning("Refusing to write through symlink: %s", target)
            return False
        block = self._gitattributes_block()
        current = ""
        try:
            if target.is_file():
                current = target.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return False
        start = current.find(_GA_BEGIN)
        end = current.find(_GA_END)
        if start >= 0 and end > start:
            before = current[:start].rstrip("\n")
            after = current[end + len(_GA_END):].lstrip("\n")
            rebuilt = "\n".join(
                part for part in (before, "\n".join(block), after) if part
            ) + "\n"
        else:
            prefix = current.rstrip("\n") + "\n\n" if current.strip() else ""
            rebuilt = prefix + "\n".join(block) + "\n"
        if rebuilt == current:
            return False
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(rebuilt, encoding="utf-8")
        except OSError:
            logger.warning("Could not write %s", target, exc_info=True)
            return False
        return True

    def origin(self, project_root: str) -> str:
        """Return the origin remote URL ("" when unknown)."""
        out = self._call(["git", "remote", "get-url", "origin"], cwd=project_root)
        if out is None:
            return ""
        url = out.strip()
        return url if _REMOTE_RE.match(url) else ""

    def pages_url(self, project_root: str) -> str:
        """Configured Pages URL, else the one inferred from the origin remote."""
        override = self._config.DOC_PAGES_URL.strip()
        if override:
            return override.rstrip("/") + "/"
        return self.infer_pages_url(self.origin(project_root))

    @staticmethod
    def infer_pages_url(remote: str) -> str:
        """Infer a GitHub/GitLab Pages URL from a remote URL.

        Args:
            remote: Remote URL (https, ssh, or git@ forms).

        Returns:
            Pages URL with a trailing slash, or "" when not inferable.
        """
        match = _REMOTE_RE.match(remote or "")
        if not match:
            return ""
        host, owner, repo = match.group(1), match.group(2), match.group(3)
        host = host.lower()
        if host in ("github.com", "www.github.com", "ssh.github.com"):
            return f"https://{owner}.github.io/{repo}/"
        if host == "gitlab.com":
            return f"https://{owner}.gitlab.io/{repo}/"
        return ""

    def _call(self, command: List[str], cwd: str) -> Optional[str]:
        """Run a command without a shell and return stdout, or None on failure."""
        try:
            result = self._run(
                command, cwd=cwd, capture_output=True, text=True,
                timeout=self._config.DOC_BRANCH_TIMEOUT_S, check=False,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        if result.returncode != 0:
            logger.debug("Command failed (%s): %s", result.returncode, " ".join(command))
            return None
        return result.stdout or ""

    def _stage_site(self, site_dir: Path, target: Path) -> List[str]:
        """Copy the site tree into the staging directory, refusing symlinks."""
        staged: List[str] = []
        for path in sorted(site_dir.rglob("*")):
            if path.is_symlink():
                logger.warning("Skipping symlink in site tree: %s", path)
                continue
            rel = path.relative_to(site_dir)
            dest = target / rel
            if path.is_dir():
                dest.mkdir(parents=True, exist_ok=True)
            elif path.is_file():
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, dest)
                staged.append(rel.as_posix())
        return staged

    def publish(self, project_root: str, push: bool = True, dry_run: bool = False) -> DocsBranchResult:
        """Stage the static site into the docs branch and optionally push.

        Args:
            project_root: Project root holding ``DIAGRAM_PAGES_DIR``.
            push: Push the branch to the remote (ignored in dry runs).
            dry_run: Stage into DOC_DRY_RUN_DIR without any git calls.

        Returns:
            DocsBranchResult describing what was staged and pushed.
        """
        cfg = self._config
        result = DocsBranchResult(branch=cfg.DOC_BRANCH_NAME)
        root = Path(project_root).resolve()
        site_dir = root / cfg.DIAGRAM_PAGES_DIR
        if not (site_dir / "index.html").is_file():
            result.message = (
                f"No site in {cfg.DIAGRAM_PAGES_DIR}/index.html yet: run `readmenator . pages` first"
            )
            return result
        self.ensure_gitattributes(str(root))
        head = read_git_head(str(root))
        result.commit = (head.get("commit") or "")[:12]
        if dry_run:
            result.pages_url = self._config.DOC_PAGES_URL.strip().rstrip("/") + "/" \
                if self._config.DOC_PAGES_URL.strip() else ""
            out = root / cfg.DOC_DRY_RUN_DIR
            if out.is_symlink():
                result.message = f"Refusing symlinked dry-run dir: {out}"
                return result
            try:
                if out.exists():
                    shutil.rmtree(out)
                out.mkdir(parents=True)
            except OSError:
                result.message = f"Could not prepare dry-run dir: {out}"
                return result
            result.files = self._stage_site(site_dir, out)
            result.output_dir = str(out)
            result.message = (
                f"Dry run: {len(result.files)} site files staged into {out}; "
                f"branch would be '{cfg.DOC_BRANCH_NAME}'"
                + (f", Pages URL {result.pages_url}" if result.pages_url else "")
            )
            return result
        result.pages_url = self.pages_url(str(root))
        result.remote = self.origin(str(root)) if push else ""
        if push and not result.remote:
            result.message = (
                "Docs branch skipped: no origin remote (add one, or set DOC_PAGES_URL for the README link)"
            )
            return result
        workdir = Path(tempfile.mkdtemp(prefix="readmenator-docbranch-"))
        try:
            stage = workdir / "site"
            stage.mkdir()
            result.files = self._stage_site(site_dir, stage)
            if not result.files:
                result.message = "Docs branch skipped: site tree is empty"
                return result
            if self._call(["git", "init", "-q"], cwd=str(stage)) is None:
                result.message = "Docs branch staging failed: git init"
                return result
            (stage / ".nojekyll").touch(exist_ok=True)
            if self._call(["git", "add", "-A"], cwd=str(stage)) is None:
                result.message = "Docs branch staging failed: git add"
                return result
            message = cfg.DOC_BRANCH_COMMIT_MESSAGE + (f" ({result.commit})" if result.commit else "")
            if self._call(["git", "-c", "user.name=readmenator", "-c", "user.email=readmenator@local",
                           "commit", "-q", "-m", message], cwd=str(stage)) is None:
                result.message = "Docs branch commit failed (git needs user.name/user.email or staged changes)"
                return result
            if push and self._call(["git", "push", "--force", result.remote,
                                    f"+HEAD:refs/heads/{cfg.DOC_BRANCH_NAME}"], cwd=str(stage)) is None:
                result.message = (
                    f"Docs branch commit ready but push to {result.remote} failed "
                    "(check credentials or `gh auth status`)"
                )
                return result
            result.pushed = bool(push)
            result.message = (
                f"Docs branch '{cfg.DOC_BRANCH_NAME}': {len(result.files)} files "
                f"{'pushed to ' + result.remote if result.pushed else 'committed locally'}"
                + (f"; Pages URL {result.pages_url}" if result.pages_url else "")
            )
            return result
        finally:
            shutil.rmtree(workdir, ignore_errors=True)
